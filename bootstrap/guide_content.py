# server commands" -- make unmistakable that these run on the server hosting MESFlow,
# not the laptop and not necessarily the same shell session as a Bootstrap/Agent step).
MACHINE_LABELS = {
    DEV: "CHẠY TRÊN MÁY DEV",
    SERVER: "CHẠY TRÊN SERVER",
    MESFLOW_SERVER: "CHẠY TRÊN SERVER MESFLOW",
    BROWSER: "TRÌNH DUYỆT (TRÊN LAPTOP)",
}


def c(machine: str, code: str, note: str | None = None) -> dict:
    """One copyable command block, labeled with the machine it runs on."""
    return {"machine": machine, "machine_label": MACHINE_LABELS[machine], "code": code.strip("\n"), "note": note}


def block(heading: str, commands: list[dict] | None = None, text: str | None = None, note: str | None = None) -> dict:
    return {"heading": heading, "commands": commands or [], "text": text, "note": note}


def step(step_id: str, num: str, title: str, purpose: str, where: str,
          blocks: list[dict], expected: str, on_error: str, next_: str) -> dict:
    return {
        "id": step_id, "num": num, "title": title, "purpose": purpose, "where": where,
        "blocks": blocks, "expected": expected, "on_error": on_error, "next": next_,
    }



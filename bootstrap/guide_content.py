def _md_text(s: str | None) -> str:
    """Convert an author-controlled HTML-ish snippet (<code>, <b>, <br>, and
    &lt;PLACEHOLDER&gt; entities used so it also renders correctly on the
    HTML page -- see the safe-render notes on guide_deployment.html) into
    plain Markdown. Markdown needs neither HTML tags nor entities."""
    if not s:
        return ""
    s = s.replace("<code>", "`").replace("</code>", "`")
    s = s.replace("<b>", "**").replace("</b>", "**")
    s = s.replace("<br>", "\n\n")
    return _html.unescape(s)


def _md_cmd(cmd_: dict) -> str:
    lines = [f"**{cmd_['machine_label']}**", "```bash", cmd_["code"], "```"]
    if cmd_.get("note"):
        lines.append(f"> {_md_text(cmd_['note'])}")
    return "\n".join(lines)


